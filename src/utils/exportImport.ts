import { AppSettings, BuyLot, CashTransaction, DailyLedgerEntry, TradeExecution } from '../types';

export interface BackupData {
  version: number;
  appName: string;
  exportedAt: string;
  counts: {
    trades: number;
    buyLots: number;
    cashTransactions: number;
  };
  settings: AppSettings;
  trades: TradeExecution[];
  buyLots: BuyLot[];
  cashTransactions: CashTransaction[];
}

/**
 * Validates a parsed backup JSON structure.
 * Returns error message if invalid, or undefined if valid.
 */
export function validateBackupSchema(data: any): { isValid: boolean; error?: string } {
  if (!data || typeof data !== 'object') {
    return { isValid: false, error: 'File content is not a valid JSON object.' };
  }

  if (data.appName !== 'PersonalStockTradingTracker') {
    return { isValid: false, error: 'Invalid backup file: Not generated by Personal Stock Trading Tracker.' };
  }

  if (!Array.isArray(data.trades)) {
    return { isValid: false, error: 'Corrupt backup: trades array is missing or invalid.' };
  }

  if (!Array.isArray(data.buyLots)) {
    return { isValid: false, error: 'Corrupt backup: buyLots array is missing or invalid.' };
  }

  if (!Array.isArray(data.cashTransactions)) {
    return { isValid: false, error: 'Corrupt backup: cashTransactions array is missing or invalid.' };
  }

  // Check some trade items if present
  for (let i = 0; i < Math.min(data.trades.length, 5); i++) {
    const t = data.trades[i];
    if (!t.id || !t.symbol || typeof t.quantity !== 'number' || typeof t.buyPrice !== 'number') {
      return { isValid: false, error: `Invalid trade structure at index ${i}.` };
    }
  }

  return { isValid: true };
}

/**
 * Triggers a client-side download for a text blob (JSON or CSV)
 */
export function triggerFileDownload(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Converts trade records to CSV string
 */
export function generateTradesCSV(trades: TradeExecution[]): string {
  const headers = [
    'Date',
    'Symbol',
    'Stock Name',
    'Type',
    'Status',
    'Quantity',
    'Buy Date',
    'Buy Time',
    'Buy Price',
    'Sell Date',
    'Sell Time',
    'Sell Price',
    'Buy Value',
    'Sell Value',
    'Gross PnL',
    'Allocated Buy Charges',
    'Sell Charges',
    'Total Charges',
    'Net PnL',
    'Manual Charges Override',
    'Notes',
  ];

  const escapeCSV = (val: any) => {
    if (val === undefined || val === null) return '';
    const str = String(val);
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const rows = trades.map((t) => {
    const buyVal = (t.quantity * t.buyPrice).toFixed(2);
    const sellVal = t.sellPrice ? (t.quantity * t.sellPrice).toFixed(2) : '0.00';

    return [
      escapeCSV(t.tradeDate),
      escapeCSV(t.symbol),
      escapeCSV(t.stockName),
      escapeCSV(t.tradeType),
      escapeCSV(t.status),
      t.quantity,
      escapeCSV(t.buyDate),
      escapeCSV(t.buyTime),
      t.buyPrice.toFixed(2),
      escapeCSV(t.sellDate || ''),
      escapeCSV(t.sellTime || ''),
      t.sellPrice !== undefined ? t.sellPrice.toFixed(2) : '',
      buyVal,
      sellVal,
      t.grossPnL.toFixed(2),
      t.buyChargesAllocated.toFixed(2),
      t.sellCharges.toFixed(2),
      t.totalCharges.toFixed(2),
      t.netPnL.toFixed(2),
      t.isManualCharges ? 'YES' : 'NO',
      escapeCSV(t.notes || ''),
    ].join(',');
  });

  return [headers.join(','), ...rows].join('\n');
}

/**
 * Converts daily ledger entries to CSV string
 */
export function generateLedgerCSV(ledger: DailyLedgerEntry[]): string {
  const headers = [
    'Date',
    'Opening Balance',
    'Deposits',
    'Withdrawals',
    'Gross Trading PnL',
    'Trading Charges',
    'Net Realized Trading PnL',
    'Trade Count',
    'Closing Balance',
    'Capital in Open Holdings',
    'Available Liquid Cash',
  ];

  const rows = ledger.map((e) => [
    e.date,
    e.openingBalance.toFixed(2),
    e.deposits.toFixed(2),
    e.withdrawals.toFixed(2),
    e.grossTradingPnL.toFixed(2),
    e.tradingCharges.toFixed(2),
    e.netTradingPnL.toFixed(2),
    e.tradeCount,
    e.closingBalance.toFixed(2),
    e.deployedCapitalInOpenHoldings.toFixed(2),
    e.availableCashBalance.toFixed(2),
  ].join(','));

  return [headers.join(','), ...rows].join('\n');
}
